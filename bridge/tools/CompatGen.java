import com.sun.source.util.JavacTask;

import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.TypeElement;
import javax.lang.model.element.TypeParameterElement;
import javax.lang.model.type.DeclaredType;
import javax.lang.model.type.ExecutableType;
import javax.lang.model.type.TypeKind;
import javax.lang.model.type.TypeMirror;
import javax.lang.model.util.Elements;
import javax.lang.model.util.Types;
import javax.tools.JavaCompiler;
import javax.tools.StandardJavaFileManager;
import javax.tools.ToolProvider;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;

/**
 * Makes the MTG United bridge compile against whatever Forge is installed (old release, new release, nightly).
 *
 * Forge's GUI interfaces (IGuiGame, IGuiBase) gain and lose methods between versions. A class that implements them
 * stops compiling as soon as Forge adds a method. So the bridge doesn't implement them directly: it extends two
 * classes this tool writes for the Forge on the classpath:
 *   GuiGameCompat extends AbstractGuiGame   - every abstract method, forwarding to onGuiCall(name, args)
 *   GuiBaseCompat implements IGuiBase       - the same for the platform interface
 * The bridge overrides the methods it knows; anything new lands in onGuiCall and gets a safe default.
 * A few "watched" methods (selection changes) are also overridden to call super and then onGuiEvent(name, args).
 *
 * It reads Forge's classes through javac's model, so it works from the Forge jar (normal use) and also from
 * Forge's sources (pass -sourcepath ...).
 *
 *   java CompatGen <outDir> -cp <forge jar(s)> [-sourcepath <forge source dirs>]
 */
public final class CompatGen {
    static final Set<String> WATCH = Set.of(
        "setSelection", "setSelectables", "clearSelectables", "setHighlighted",
        "setWeaklySelectable", "clearWeaklySelectable", "setUsedToPay");

    public static void main(final String[] args) throws IOException {
        if (args.length < 1) { System.err.println("usage: CompatGen <outDir> -cp <classpath> [-sourcepath <dirs>]"); System.exit(2); }
        final Path out = Path.of(args[0]);
        final List<String> opts = new ArrayList<>(List.of("-proc:none", "-implicit:none"));
        for (int i = 1; i < args.length; i++) { opts.add(args[i]); }

        final JavaCompiler jc = ToolProvider.getSystemJavaCompiler();
        if (jc == null) { System.err.println("CompatGen needs a JDK (javac), not just a JRE."); System.exit(3); }
        final StandardJavaFileManager fm = jc.getStandardFileManager(null, null, StandardCharsets.UTF_8);
        final JavacTask task = (JavacTask) jc.getTask(null, fm, d -> { }, opts, null, null);
        final Elements el = task.getElements();
        final Types ty = task.getTypes();

        final TypeElement gameBase = el.getTypeElement("forge.gamemodes.match.AbstractGuiGame");
        final TypeElement guiBase = el.getTypeElement("forge.gui.interfaces.IGuiBase");
        if (gameBase == null || guiBase == null) {
            System.err.println("Forge's GUI classes weren't found on the classpath (is this a Forge jar?).");
            System.exit(4);
        }
        Files.createDirectories(out);
        write(out.resolve("GuiGameCompat.java"), generate(el, ty, gameBase, "GuiGameCompat", "extends " + gameBase.getQualifiedName(), true));
        write(out.resolve("GuiBaseCompat.java"), generate(el, ty, guiBase, "GuiBaseCompat", "implements " + guiBase.getQualifiedName(), false));
        System.out.println("Compatibility layer written for this Forge: " + out.toAbsolutePath());
    }

    static void write(final Path p, final String s) throws IOException {
        Files.writeString(p, s, StandardCharsets.UTF_8);
    }

    static String generate(final Elements el, final Types ty, final TypeElement base, final String name, final String heritage, final boolean watch) {
        final DeclaredType baseType = (DeclaredType) base.asType();
        final List<ExecutableElement> all = new ArrayList<>();
        for (final Element e : el.getAllMembers(base)) {
            if (e.getKind() == ElementKind.METHOD) { all.add((ExecutableElement) e); }
        }
        final StringBuilder sb = new StringBuilder();
        sb.append("package mtgunited.bridge;\n\n");
        sb.append("// GENERATED by bridge/tools/CompatGen.java for the installed Forge. Do not edit; setup regenerates it.\n");
        sb.append("@SuppressWarnings({\"unchecked\", \"rawtypes\", \"deprecation\", \"removal\"})\n");
        sb.append("public abstract class ").append(name).append(' ').append(heritage).append(" {\n");
        sb.append("    /** A Forge call the bridge has no method for (new in this Forge): return a value or null for the default. */\n");
        sb.append("    protected abstract Object onGuiCall(String method, Object[] args);\n");
        if (watch) {
            sb.append("    /** A watched Forge call (selection changes...), after Forge's own handling. */\n");
            sb.append("    protected abstract void onGuiEvent(String method, Object[] args);\n");
        }
        final Set<String> done = new java.util.HashSet<>();
        for (final ExecutableElement m : all) {
            final Set<Modifier> mods = m.getModifiers();
            if (mods.contains(Modifier.STATIC) || mods.contains(Modifier.PRIVATE) || mods.contains(Modifier.FINAL)) { continue; }
            if (m.getEnclosingElement().toString().equals("java.lang.Object")) { continue; }
            final boolean isAbstract = mods.contains(Modifier.ABSTRACT) && !implemented(el, all, m, base);
            final boolean watched = watch && !isAbstract && WATCH.contains(m.getSimpleName().toString())
                && m.getReturnType().getKind() == TypeKind.VOID && !mods.contains(Modifier.ABSTRACT);
            if (!isAbstract && !watched) { continue; }
            final ExecutableType et = (ExecutableType) ty.asMemberOf(baseType, m);
            final String sig = signature(m, et);
            if (!done.add(m.getSimpleName() + erasure(ty, et))) { continue; }
            sb.append("    ").append(sig).append(" {\n");
            final String argArray = argArray(m);
            if (watched) {
                sb.append("        super.").append(m.getSimpleName()).append('(').append(argNames(m)).append(");\n");
                sb.append("        onGuiEvent(\"").append(m.getSimpleName()).append("\", ").append(argArray).append(");\n");
            } else {
                final TypeMirror rt = et.getReturnType();
                final String call = "onGuiCall(\"" + m.getSimpleName() + "\", " + argArray + ")";
                switch (rt.getKind()) {
                    case VOID -> sb.append("        ").append(call).append(";\n");
                    case BOOLEAN -> sb.append("        final Object r = ").append(call).append(";\n        return r instanceof Boolean b && b;\n");
                    case INT, LONG, SHORT, BYTE, FLOAT, DOUBLE -> sb.append("        final Object r = ").append(call)
                        .append(";\n        return r instanceof Number n ? n.").append(rt.getKind().name().toLowerCase()).append("Value() : 0;\n");
                    case CHAR -> sb.append("        final Object r = ").append(call).append(";\n        return r instanceof Character c ? c : (char) 0;\n");
                    default -> sb.append("        return (").append(rt).append(") ").append(call).append(";\n");
                }
            }
            sb.append("    }\n");
        }
        sb.append("}\n");
        return sb.toString();
    }

    /** Is this abstract method already implemented by a concrete method (class body or interface default)? */
    static boolean implemented(final Elements el, final List<ExecutableElement> all, final ExecutableElement m, final TypeElement base) {
        for (final ExecutableElement c : all) {
            if (c == m || !c.getSimpleName().equals(m.getSimpleName())) { continue; }
            if (c.getModifiers().contains(Modifier.ABSTRACT)) { continue; }
            if (el.overrides(c, m, base)) { return true; }
        }
        return false;
    }

    static String erasure(final Types ty, final ExecutableType et) {
        final StringBuilder sb = new StringBuilder("(");
        for (final TypeMirror p : et.getParameterTypes()) { sb.append(ty.erasure(p)).append(','); }
        return sb.append(')').toString();
    }

    static String signature(final ExecutableElement m, final ExecutableType et) {
        final StringBuilder sb = new StringBuilder();
        sb.append(m.getModifiers().contains(Modifier.PROTECTED) ? "protected " : "public ");
        if (!m.getTypeParameters().isEmpty()) {
            sb.append('<');
            for (int i = 0; i < m.getTypeParameters().size(); i++) {
                final TypeParameterElement tp = m.getTypeParameters().get(i);
                if (i > 0) { sb.append(", "); }
                sb.append(tp.getSimpleName());
                final List<? extends TypeMirror> bounds = tp.getBounds();
                final List<String> b = new ArrayList<>();
                for (final TypeMirror t : bounds) { if (!t.toString().equals("java.lang.Object")) { b.add(t.toString()); } }
                if (!b.isEmpty()) { sb.append(" extends ").append(String.join(" & ", b)); }
            }
            sb.append("> ");
        }
        sb.append(et.getReturnType()).append(' ').append(m.getSimpleName()).append('(');
        final List<? extends TypeMirror> ps = et.getParameterTypes();
        for (int i = 0; i < ps.size(); i++) {
            if (i > 0) { sb.append(", "); }
            String t = ps.get(i).toString();
            if (m.isVarArgs() && i == ps.size() - 1 && t.endsWith("[]")) { t = t.substring(0, t.length() - 2) + "..."; }
            sb.append(t).append(" a").append(i);
        }
        sb.append(')');
        if (!m.getThrownTypes().isEmpty()) {
            sb.append(" throws ");
            for (int i = 0; i < m.getThrownTypes().size(); i++) { if (i > 0) { sb.append(", "); } sb.append(m.getThrownTypes().get(i)); }
        }
        return sb.toString();
    }

    static String argNames(final ExecutableElement m) {
        final StringBuilder sb = new StringBuilder();
        for (int i = 0; i < m.getParameters().size(); i++) { if (i > 0) { sb.append(", "); } sb.append('a').append(i); }
        return sb.toString();
    }

    static String argArray(final ExecutableElement m) {
        return m.getParameters().isEmpty() ? "new Object[0]" : "new Object[] { " + argNames(m) + " }";
    }
}
